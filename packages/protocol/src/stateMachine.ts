export interface CreateSessaoInput {
  readonly participanteId: string;
  readonly name: string;
  readonly protocolVersion: number;
  readonly joinNonce: string;
  /** Injectable for deterministic tests; normally generated by `generateCodigoDeSessao`. */
  readonly codigoDeSessao: string;
}

export type CreateSessaoResult =
  | { readonly state: SessaoState; readonly effects: readonly Effect[] }
  | { readonly state: null; readonly effects: readonly Effect[] };

export function createSessao(input: CreateSessaoInput): CreateSessaoResult {
  if (input.protocolVersion !== PROTOCOL_VERSION) {
    return {
      state: null,
      effects: [
        {
          toParticipanteIds: [input.participanteId],
          message: { type: "entry-refused", reason: "incompatible-version" },
        },
      ],
    };
  }

  const anfitriao: InternalParticipante = {
    id: input.participanteId,
    name: input.name,
    state: "admitted",
    joinNonce: input.joinNonce,
    fallenAt: null,
  };

  const state: SessaoState = {
    codigoDeSessao: input.codigoDeSessao,
    protocolVersion: PROTOCOL_VERSION,
    anfitriaoId: input.participanteId,
    participantes: new Map([[anfitriao.id, anfitriao]]),
    transmissores: [],
    ended: false,
  };

  return {
    state,
    effects: [
      {
        toParticipanteIds: [input.participanteId],
        message: {
          type: "sessao-created",
          codigoDeSessao: input.codigoDeSessao,
          participanteId: input.participanteId,
        },
      },
    ],
  };
}

